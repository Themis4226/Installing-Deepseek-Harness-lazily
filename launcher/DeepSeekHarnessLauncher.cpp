bool EnsureDirectory(const std::filesystem::path& path, std::wstring& errorText) {
    std::error_code error;
    if (std::filesystem::create_directories(path, error) || DirectoryExists(path)) {
        return true;
    }
    const std::string message = error.message();
    errorText = L"无法创建目录：" + path.wstring() + L"\n" + std::wstring(message.begin(), message.end());
    return false;
}

bool IsSafeRuntimeId(const std::wstring& value) {
    if (value == L"bundled") {
        return true;
    }
    if (value.empty() || value.size() > 80 || value.find(L"..") != std::wstring::npos) {
        return false;
    }
    return std::all_of(value.begin(), value.end(), [](wchar_t character) {
        return (character >= L'a' && character <= L'z') ||
            (character >= L'A' && character <= L'Z') ||
            (character >= L'0' && character <= L'9') ||
            character == L'.' || character == L'+' || character == L'-' || character == L'_';
    });
}

bool ReadSmallTextFile(const std::filesystem::path& path, std::string& text) {
    std::error_code sizeError;
    const auto size = std::filesystem::file_size(path, sizeError);
    if (sizeError || size > 1024 * 1024) {
        return false;
    }
    std::ifstream input(path, std::ios::binary);
    if (!input) {
        return false;
    }
    text.assign(std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>());
    return input.good() || input.eof();
}

bool ParsePackageVersion(const std::filesystem::path& packagePath, std::wstring& version) {
    std::string text;
    if (!ReadSmallTextFile(packagePath, text)) {
        return false;
    }
    const size_t key = text.find("\"version\"");
    if (key == std::string::npos) {
        return false;
    }
    const size_t colon = text.find(':', key + 9);
    const size_t quote = colon == std::string::npos ? std::string::npos : text.find('"', colon + 1);
    const size_t end = quote == std::string::npos ? std::string::npos : text.find('"', quote + 1);
    if (quote == std::string::npos || end == std::string::npos || end == quote + 1) {
        return false;
    }
    const std::string value = text.substr(quote + 1, end - quote - 1);
    version.assign(value.begin(), value.end());
    return IsSafeRuntimeId(version) && version != L"bundled";
}


std::filesystem::path FindNodeExecutable(std::wstring& errorText) {
    std::vector<std::filesystem::path> candidates;

    wchar_t explicitPath[32768]{};
    const DWORD explicitLength = GetEnvironmentVariableW(L"NODE_EXE", explicitPath, ARRAYSIZE(explicitPath));
    if (explicitLength > 0 && explicitLength < ARRAYSIZE(explicitPath)) {
        AddNodeCandidate(candidates, explicitPath);
    }

    AddNodeCandidate(candidates, ExecutableDirectory() / kBundledNodeRelativePath);

    AddNodeCandidatesFromPath(candidates);

    wchar_t programFiles[32768]{};
    if (GetEnvironmentVariableW(L"ProgramFiles", programFiles, ARRAYSIZE(programFiles)) > 0) {
        AddNodeCandidate(candidates, std::filesystem::path(programFiles) / L"nodejs" / L"node.exe");
    }
    wchar_t programFilesX86[32768]{};
    if (GetEnvironmentVariableW(L"ProgramFiles(x86)", programFilesX86, ARRAYSIZE(programFilesX86)) > 0) {
        AddNodeCandidate(candidates, std::filesystem::path(programFilesX86) / L"nodejs" / L"node.exe");
    }

    std::wstring rejected;
    for (const auto& candidate : candidates) {
        NodeVersion version{};
        std::wstring displayVersion;
        std::wstring architecture;
        if (QueryNodeRuntime(candidate, version, displayVersion, architecture) &&
            IsSupportedNodeVersion(version) && architecture == L"x64") {
            return candidate;
        }
        if (!rejected.empty()) {
            rejected += L"\n";
        }
        rejected += candidate.wstring();
        if (!displayVersion.empty()) {
            rejected += L"（" + displayVersion;
            if (!architecture.empty()) {
                rejected += L"，" + architecture;
            }
            rejected += L"）";
        } else {
            rejected += L"（无法读取版本）";
        }
    }

    if (candidates.empty()) {
        errorText = L"找不到 node.exe。Lite x64 版需要已安装 x64 Node.js 22.19+ 或 24+。";
    } else {
        errorText = L"没有找到兼容的 Node.js。Lite x64 版需要 x64 Node.js 22.19+ 或 24+。\n检测结果：\n" + rejected;
    }
    return {};
}

std::wstring QuoteTextArgument(std::wstring_view text) {
    std::wstring quoted = L"\"";
    size_t backslashes = 0;
    for (const wchar_t character : text) {
        if (character == L'\\') {
            ++backslashes;
            continue;
        }
        if (character == L'\"') {
            quoted.append(backslashes * 2 + 1, L'\\');
            quoted.push_back(L'\"');
            backslashes = 0;
            continue;
        }
        quoted.append(backslashes, L'\\');
        backslashes = 0;
        quoted.push_back(character);
    }
    quoted.append(backslashes * 2, L'\\');
    quoted.push_back(L'\"');
    return quoted;
}

std::wstring QuoteArgument(const std::filesystem::path& value) {
    return QuoteTextArgument(value.wstring());
}

std::wstring Utf8ToWide(std::string_view text) {
    if (text.empty()) {
        return {};
    }
    const int required = MultiByteToWideChar(
        CP_UTF8, MB_ERR_INVALID_CHARS, text.data(), static_cast<int>(text.size()), nullptr, 0);
    if (required <= 0) {
        return std::wstring(text.begin(), text.end());
    }
    std::wstring result(static_cast<size_t>(required), L'\0');
    MultiByteToWideChar(
        CP_UTF8, MB_ERR_INVALID_CHARS, text.data(), static_cast<int>(text.size()), result.data(), required);
    return result;
}

std::wstring ReadEnvironmentValue(const wchar_t* name) {
    const DWORD required = GetEnvironmentVariableW(name, nullptr, 0);
    if (required == 0 || required > 32768) {
        return {};
    }
    std::vector<wchar_t> buffer(required);
    const DWORD length = GetEnvironmentVariableW(name, buffer.data(), required);
    if (length == 0 || length >= required) {
        return {};
    }
    return std::wstring(buffer.data(), length);
}

bool BuildChildEnvironment(
    const wchar_t* overrideName,
    const std::wstring& overrideValue,
    std::vector<wchar_t>& block,
    std::wstring& errorText) {
    block.clear();
    LPWCH rawEnvironment = GetEnvironmentStringsW();
    if (rawEnvironment == nullptr) {
        errorText = L"无法读取 DSH 子进程环境：" + FormatSystemError(GetLastError());
        return false;
    }

    const std::wstring overridePrefix = std::wstring(overrideName) + L"=";
    std::vector<std::wstring> entries;
    for (const wchar_t* cursor = rawEnvironment; *cursor != L'\0';) {
        std::wstring entry(cursor);
        cursor += entry.size() + 1;
        if (entry.size() >= overridePrefix.size() &&
            _wcsnicmp(entry.c_str(), overridePrefix.c_str(), overridePrefix.size()) == 0) {
            continue;
        }
        entries.push_back(std::move(entry));
    }
    FreeEnvironmentStringsW(rawEnvironment);

    entries.push_back(overridePrefix + overrideValue);
    std::sort(entries.begin(), entries.end(), [](const std::wstring& left, const std::wstring& right) {
        return _wcsicmp(left.c_str(), right.c_str()) < 0;
    });
    size_t totalCharacters = 1;
    for (const auto& entry : entries) {
        totalCharacters += entry.size() + 1;
    }
    block.reserve(totalCharacters);
    for (const auto& entry : entries) {
        block.insert(block.end(), entry.begin(), entry.end());
        block.push_back(L'\0');
    }
    block.push_back(L'\0');
    return true;
}


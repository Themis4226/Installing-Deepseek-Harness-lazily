bool IsTrustedBridgeSource(const wchar_t* uri) {
    if (uri == nullptr || g_dshPort == 0) {
        return false;
    }
    const std::wstring expectedOrigin = L"http://127.0.0.1:" + std::to_wstring(g_dshPort);
    const size_t expectedLength = expectedOrigin.size();
    if (_wcsnicmp(uri, expectedOrigin.c_str(), expectedLength) != 0) {
        return false;
    }
    const wchar_t boundary = uri[expectedLength];
    return boundary == L'\0' || boundary == L'/' || boundary == L'?' || boundary == L'#';
}

bool IsSafeWebVersion(const std::wstring& value) {
    return value.size() <= 64 && std::all_of(value.begin(), value.end(), [](wchar_t character) {
        return (character >= L'a' && character <= L'z') ||
            (character >= L'A' && character <= L'Z') ||
            (character >= L'0' && character <= L'9') ||
            character == L'.' || character == L'+' || character == L'-';
    });
}


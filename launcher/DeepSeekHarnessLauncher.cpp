bool IsInternalUri(std::wstring uri) {
    std::transform(uri.begin(), uri.end(), uri.begin(), [](wchar_t value) {
        return static_cast<wchar_t>(towlower(value));
    });
    if (uri == L"about:blank") {
        return true;
    }
    if (g_dshPort == 0) {
        return false;
    }
    const std::wstring origin = L"http://127.0.0.1:" + std::to_wstring(g_dshPort);
    const std::wstring localhostOrigin = L"http://localhost:" + std::to_wstring(g_dshPort);
    const auto startsWithOrigin = [&uri](const std::wstring& allowedOrigin) {
        if (uri.compare(0, allowedOrigin.size(), allowedOrigin) != 0) {
            return false;
        }
        if (uri.size() == allowedOrigin.size()) {
            return true;
        }
        const wchar_t next = uri[allowedOrigin.size()];
        return next == L'/' || next == L'?' || next == L'#';
    };
    return startsWithOrigin(origin) || startsWithOrigin(localhostOrigin) ||
        uri.rfind(L"blob:" + origin, 0) == 0 || uri.rfind(L"blob:" + localhostOrigin, 0) == 0;
}

void OpenExternalUri(const wchar_t* uri) {
    if (uri == nullptr) {
        return;
    }
    std::wstring normalized(uri);
    std::transform(normalized.begin(), normalized.end(), normalized.begin(), [](wchar_t value) {
        return static_cast<wchar_t>(towlower(value));
    });
    if (normalized.rfind(L"https://", 0) == 0 || normalized.rfind(L"http://", 0) == 0) {
        ShellExecuteW(g_window, L"open", uri, nullptr, nullptr, SW_SHOWNORMAL);
    }
}


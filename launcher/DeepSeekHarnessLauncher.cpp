struct NodeVersion {
    unsigned long major = 0;
    unsigned long minor = 0;
    unsigned long patch = 0;
};

bool ParseNodeVersion(std::string_view text, NodeVersion& version) {
    size_t position = text.find('v');
    if (position == std::string_view::npos) {
        position = 0;
    } else {
        ++position;
    }

    auto readPart = [&](unsigned long& value) -> bool {
        if (position >= text.size() || !std::isdigit(static_cast<unsigned char>(text[position]))) {
            return false;
        }
        value = 0;
        while (position < text.size() && std::isdigit(static_cast<unsigned char>(text[position]))) {
            value = value * 10 + static_cast<unsigned long>(text[position] - '0');
            ++position;
        }
        return true;
    };

    if (!readPart(version.major) || position >= text.size() || text[position++] != '.' ||
        !readPart(version.minor) || position >= text.size() || text[position++] != '.' ||
        !readPart(version.patch)) {
        return false;
    }
    if (position < text.size() && text[position] == '-') {
        return false;
    }
    return true;
}

bool IsSupportedNodeVersion(const NodeVersion& version) {
    return (version.major == 22 && version.minor >= 19) || version.major >= 24;
}

bool QueryNodeRuntime(
    const std::filesystem::path& executable,
    NodeVersion& version,
    std::wstring& displayVersion,
    std::wstring& architecture) {
    SECURITY_ATTRIBUTES security{};
    security.nLength = sizeof(security);
    security.bInheritHandle = TRUE;

    HANDLE outputRead = nullptr;
    HANDLE outputWrite = nullptr;
    if (!CreatePipe(&outputRead, &outputWrite, &security, 0) ||
        !SetHandleInformation(outputRead, HANDLE_FLAG_INHERIT, 0)) {
        if (outputRead != nullptr) CloseHandle(outputRead);
        if (outputWrite != nullptr) CloseHandle(outputWrite);
        return false;
    }

    std::wstring commandLine =
        QuoteArgument(executable) + L" -p \"process.version + ' ' + process.arch\"";
    std::vector<wchar_t> mutableCommand(commandLine.begin(), commandLine.end());
    mutableCommand.push_back(L'\0');

    STARTUPINFOW startup{};
    startup.cb = sizeof(startup);
    startup.dwFlags = STARTF_USESTDHANDLES | STARTF_USESHOWWINDOW;
    startup.wShowWindow = SW_HIDE;
    startup.hStdInput = GetStdHandle(STD_INPUT_HANDLE);
    startup.hStdOutput = outputWrite;
    startup.hStdError = outputWrite;

    PROCESS_INFORMATION process{};
    const BOOL created = CreateProcessW(
        executable.c_str(),
        mutableCommand.data(),
        nullptr,
        nullptr,
        TRUE,
        CREATE_NO_WINDOW | CREATE_UNICODE_ENVIRONMENT,
        nullptr,
        nullptr,
        &startup,
        &process);
    CloseHandle(outputWrite);
    if (!created) {
        CloseHandle(outputRead);
        return false;
    }

    CloseHandle(process.hThread);
    const DWORD waitResult = WaitForSingleObject(process.hProcess, 5000);
    if (waitResult != WAIT_OBJECT_0) {
        TerminateProcess(process.hProcess, 1);
        WaitForSingleObject(process.hProcess, 1000);
    }

    std::string output;
    char buffer[256]{};
    DWORD bytesRead = 0;
    while (output.size() < 4096 && ReadFile(outputRead, buffer, sizeof(buffer), &bytesRead, nullptr) && bytesRead > 0) {
        output.append(buffer, bytesRead);
    }
    CloseHandle(outputRead);

    DWORD exitCode = 1;
    GetExitCodeProcess(process.hProcess, &exitCode);
    CloseHandle(process.hProcess);
    if (waitResult != WAIT_OBJECT_0 || exitCode != 0 || !ParseNodeVersion(output, version)) {
        return false;
    }

    const size_t lineEnd = output.find_first_of("\r\n");
    const std::string concise = output.substr(0, lineEnd);
    const size_t separator = concise.find(' ');
    if (separator == std::string::npos || separator + 1 >= concise.size()) {
        return false;
    }
    displayVersion.assign(concise.begin(), concise.begin() + static_cast<std::ptrdiff_t>(separator));
    architecture.assign(concise.begin() + static_cast<std::ptrdiff_t>(separator + 1), concise.end());
    return true;
}

void AddNodeCandidate(
    std::vector<std::filesystem::path>& candidates,
    const std::filesystem::path& candidate) {
    if (!FileExists(candidate)) {
        return;
    }
    for (const auto& existing : candidates) {
        if (_wcsicmp(existing.c_str(), candidate.c_str()) == 0) {
            return;
        }
    }
    candidates.push_back(candidate);
}

void AddNodeCandidatesFromPath(std::vector<std::filesystem::path>& candidates) {
    const DWORD required = GetEnvironmentVariableW(L"PATH", nullptr, 0);
    if (required == 0) {
        return;
    }
    std::vector<wchar_t> buffer(required);
    const DWORD length = GetEnvironmentVariableW(L"PATH", buffer.data(), required);
    if (length == 0 || length >= required) {
        return;
    }

    const std::wstring pathValue(buffer.data(), length);
    size_t start = 0;
    while (start <= pathValue.size()) {
        const size_t end = pathValue.find(L';', start);
        std::wstring entry = pathValue.substr(start, end == std::wstring::npos ? end : end - start);
        while (!entry.empty() && std::iswspace(entry.front())) entry.erase(entry.begin());
        while (!entry.empty() && std::iswspace(entry.back())) entry.pop_back();
        if (entry.size() >= 2 && entry.front() == L'"' && entry.back() == L'"') {
            entry = entry.substr(1, entry.size() - 2);
        }

        // Empty PATH elements represent the current directory; skip them so an
        // unrelated node.exe beside the launcher cannot be selected implicitly.
        if (!entry.empty()) {
            const DWORD expandedRequired = ExpandEnvironmentStringsW(entry.c_str(), nullptr, 0);
            if (expandedRequired > 0) {
                std::vector<wchar_t> expanded(expandedRequired);
                if (ExpandEnvironmentStringsW(entry.c_str(), expanded.data(), expandedRequired) > 0) {
                    AddNodeCandidate(candidates, std::filesystem::path(expanded.data()) / L"node.exe");
                }
            }
        }

        if (end == std::wstring::npos) {
            break;
        }
        start = end + 1;
    }
}


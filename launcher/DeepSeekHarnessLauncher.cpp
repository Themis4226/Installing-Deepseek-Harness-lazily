bool AtomicWriteTextFile(
    const std::filesystem::path& destination,
    const std::string& text,
    std::wstring& errorText) {
    if (!EnsureDirectory(destination.parent_path(), errorText)) {
        return false;
    }
    const auto temporary = destination.wstring() + L".tmp";
    HANDLE file = CreateFileW(
        temporary.c_str(),
        GENERIC_WRITE,
        0,
        nullptr,
        CREATE_ALWAYS,
        FILE_ATTRIBUTE_NORMAL,
        nullptr);
    if (file == INVALID_HANDLE_VALUE) {
        errorText = L"无法写入运行时状态临时文件：" + FormatSystemError(GetLastError());
        return false;
    }
    DWORD written = 0;
    const BOOL writeResult = WriteFile(
        file,
        text.data(),
        static_cast<DWORD>(text.size()),
        &written,
        nullptr);
    const BOOL flushResult = writeResult && written == text.size() && FlushFileBuffers(file);
    const DWORD writeError = flushResult ? ERROR_SUCCESS : GetLastError();
    CloseHandle(file);
    if (!flushResult) {
        DeleteFileW(temporary.c_str());
        errorText = L"写入运行时状态失败：" + FormatSystemError(writeError);
        return false;
    }
    if (!MoveFileExW(
            temporary.c_str(),
            destination.c_str(),
            MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH)) {
        const DWORD moveError = GetLastError();
        DeleteFileW(temporary.c_str());
        errorText = L"原子切换运行时状态失败：" + FormatSystemError(moveError);
        return false;
    }
    return true;
}

RuntimeState LoadRuntimeState() {
    RuntimeState state;
    std::string text;
    if (!ReadSmallTextFile(RuntimeStatePath(), text)) {
        return state;
    }

    bool schemaValid = false;
    size_t position = 0;
    while (position <= text.size()) {
        const size_t end = text.find('\n', position);
        std::string line = text.substr(position, end == std::string::npos ? end : end - position);
        if (!line.empty() && line.back() == '\r') {
            line.pop_back();
        }
        const size_t separator = line.find('=');
        if (separator != std::string::npos) {
            const std::string key = line.substr(0, separator);
            const std::string value = line.substr(separator + 1);
            if (key == "schema") {
                schemaValid = value == "1";
            } else if (key == "active") {
                state.active.assign(value.begin(), value.end());
            } else if (key == "previous") {
                state.previous.assign(value.begin(), value.end());
            } else if (key == "pending") {
                state.pending = value == "1";
            } else if (key == "attempts") {
                try {
                    const unsigned long parsed = std::stoul(value);
                    state.attempts = parsed <= 100 ? static_cast<unsigned int>(parsed) : 100;
                } catch (...) {
                    state.attempts = 100;
                }
            }
        }
        if (end == std::string::npos) {
            break;
        }
        position = end + 1;
    }
    if (!schemaValid || !IsSafeRuntimeId(state.active) || !IsSafeRuntimeId(state.previous)) {
        return RuntimeState{};
    }
    return state;
}

bool WriteRuntimeState(const RuntimeState& state, std::wstring& errorText) {
    if (!IsSafeRuntimeId(state.active) || !IsSafeRuntimeId(state.previous)) {
        errorText = L"拒绝写入包含非法版本标识的运行时状态。";
        return false;
    }
    const auto narrow = [](const std::wstring& value) {
        std::string result;
        result.reserve(value.size());
        for (const wchar_t character : value) {
            result.push_back(static_cast<char>(character));
        }
        return result;
    };
    const std::string text =
        "schema=1\nactive=" + narrow(state.active) +
        "\nprevious=" + narrow(state.previous) +
        "\npending=" + (state.pending ? std::string("1") : std::string("0")) +
        "\nattempts=" + std::to_string(state.attempts) + "\n";
    return AtomicWriteTextFile(RuntimeStatePath(), text, errorText);
}

bool ValidateManagedRuntime(
    const std::wstring& runtimeId,
    std::filesystem::path& entry,
    std::wstring& errorText) {
    if (!IsSafeRuntimeId(runtimeId) || runtimeId == L"bundled") {
        errorText = L"非法的托管运行时版本标识。";
        return false;
    }
    const auto runtimeRoot = ManagedRuntimeDirectory(runtimeId);
    entry = runtimeRoot / kDshRelativePath;
    if (!FileExists(entry)) {
        errorText = L"托管运行时缺少 DSH 入口：" + entry.wstring();
        return false;
    }
    std::wstring packageVersion;
    if (!ParsePackageVersion(runtimeRoot / L"node_modules\\@deepseek-ai\\dsh\\package.json", packageVersion) ||
        packageVersion != runtimeId) {
        errorText = L"托管运行时版本与目录不一致：" + runtimeId;
        return false;
    }
    return true;
}

bool PrepareRuntimeForLaunch(std::wstring& errorText) {
    RuntimeState state = LoadRuntimeState();
    bool changed = false;
    if (state.pending) {
        if (state.attempts >= 1) {
            state.active = state.previous;
            state.pending = false;
            state.attempts = 0;
        } else {
            state.attempts = 1;
        }
        changed = true;
    }

    std::filesystem::path entry;
    if (state.active == L"bundled") {
        entry = g_appRoot / kDshRelativePath;
    } else {
        std::wstring validationError;
        if (!ValidateManagedRuntime(state.active, entry, validationError)) {
            std::filesystem::path previousEntry;
            if (state.previous != L"bundled" &&
                ValidateManagedRuntime(state.previous, previousEntry, validationError)) {
                state.active = state.previous;
                entry = std::move(previousEntry);
            } else {
                state.active = L"bundled";
                entry = g_appRoot / kDshRelativePath;
            }
            state.pending = false;
            state.attempts = 0;
            changed = true;
        }
    }
    if (!FileExists(entry)) {
        errorText = L"找不到可用的 DSH 运行时：\n" + entry.wstring();
        return false;
    }
    if (changed && !WriteRuntimeState(state, errorText)) {
        return false;
    }
    g_runtimeState = state;
    g_activeRuntimeId = state.active;
    g_activeDshEntry = std::move(entry);
    return true;
}

bool MarkRuntimeHealthy(std::wstring& errorText) {
    RuntimeState state = LoadRuntimeState();
    if (!state.pending || state.active != g_activeRuntimeId) {
        return true;
    }
    state.pending = false;
    state.attempts = 0;
    if (!WriteRuntimeState(state, errorText)) {
        return false;
    }
    g_runtimeState = state;
    return true;
}

bool RollbackPendingRuntime(std::wstring& errorText) {
    RuntimeState state = LoadRuntimeState();
    if (!state.pending) {
        return false;
    }
    state.active = state.previous;
    state.pending = false;
    state.attempts = 0;
    if (!WriteRuntimeState(state, errorText)) {
        return false;
    }
    g_runtimeState = state;
    return true;
}

bool ActivatePreparedRuntime(const std::wstring& runtimeId, std::wstring& errorText) {
    std::filesystem::path entry;
    if (!ValidateManagedRuntime(runtimeId, entry, errorText)) {
        return false;
    }
    RuntimeState state = LoadRuntimeState();
    if (state.pending) {
        errorText = L"上一项运行时更新仍在健康检查中，拒绝覆盖可回退版本。";
        return false;
    }
    if (state.active == runtimeId && !state.pending) {
        g_runtimeState = state;
        g_activeRuntimeId = runtimeId;
        g_activeDshEntry = std::move(entry);
        return true;
    }
    state.previous = state.active;
    state.active = runtimeId;
    state.pending = true;
    state.attempts = 0;
    if (!WriteRuntimeState(state, errorText)) {
        return false;
    }
    g_runtimeState = state;
    g_activeRuntimeId = runtimeId;
    g_activeDshEntry = std::move(entry);
    return true;
}


std::filesystem::path LauncherDataRoot() {
    wchar_t explicitPath[32768]{};
    const DWORD explicitLength = GetEnvironmentVariableW(
        kDataHomeEnvironmentVariable, explicitPath, ARRAYSIZE(explicitPath));
    if (explicitLength > 0 && explicitLength < ARRAYSIZE(explicitPath)) {
        return explicitPath;
    }

    // Preserve the existing local profile for this development copy. Clean release
    // archives do not contain this directory and therefore use LocalAppData.
    const auto executableRoot = ExecutableDirectory();
    if (DirectoryExists(executableRoot / kWebViewDataRelativePath)) {
        return executableRoot;
    }

    PWSTR localAppData = nullptr;
    if (SUCCEEDED(SHGetKnownFolderPath(FOLDERID_LocalAppData, KF_FLAG_CREATE, nullptr, &localAppData)) &&
        localAppData != nullptr) {
        std::filesystem::path result = std::filesystem::path(localAppData) / kLocalDataDirectoryName;
        CoTaskMemFree(localAppData);
        return result;
    }
    if (localAppData != nullptr) {
        CoTaskMemFree(localAppData);
    }
    return executableRoot;
}


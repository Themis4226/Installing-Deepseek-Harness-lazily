bool ResolveUpdateManifests(
    std::wstring& runtimeManifest,
    std::wstring& launcherManifest,
    bool& testMode,
    std::wstring& errorText) {
    testMode = ReadEnvironmentValue(kUpdateTestModeEnvironmentVariable) == L"1";
    if (!testMode) {
        runtimeManifest = kUpdateManifestUrl;
        launcherManifest = kLauncherUpdateManifestUrl;
        return true;
    }
    runtimeManifest = ReadEnvironmentValue(kUpdateManifestEnvironmentVariable);
    launcherManifest = ReadEnvironmentValue(kLauncherUpdateManifestEnvironmentVariable);
    const auto allowedTestUrl = [](std::wstring value) {
        std::transform(value.begin(), value.end(), value.begin(), [](wchar_t character) {
            return static_cast<wchar_t>(towlower(character));
        });
        return value.rfind(L"file:///", 0) == 0 ||
            value.rfind(L"http://127.0.0.1:", 0) == 0 ||
            value.rfind(L"http://localhost:", 0) == 0;
    };
    if (!allowedTestUrl(runtimeManifest) || !allowedTestUrl(launcherManifest)) {
        errorText = L"测试更新源仅允许 file:///、127.0.0.1 或 localhost，且必须同时提供两个清单。";
        return false;
    }
    return true;
}

void DrainUpdaterOutput(HANDLE outputRead, std::string& output) {
    constexpr size_t kMaximumCapturedOutput = 1024 * 1024;
    char buffer[4096]{};
    for (;;) {
        DWORD available = 0;
        if (!PeekNamedPipe(outputRead, nullptr, 0, nullptr, &available, nullptr) || available == 0) {
            return;
        }
        const DWORD requested = std::min<DWORD>(available, static_cast<DWORD>(sizeof(buffer)));
        DWORD bytesRead = 0;
        if (!ReadFile(outputRead, buffer, requested, &bytesRead, nullptr) || bytesRead == 0) {
            return;
        }
        if (output.size() < kMaximumCapturedOutput) {
            const size_t retained = std::min<size_t>(bytesRead, kMaximumCapturedOutput - output.size());
            output.append(buffer, retained);
        }
    }
}

bool NormalizeUpdaterProtocol(std::string& output) {
    const size_t first = output.find_first_not_of(" \t\r\n");
    const size_t last = output.find_last_not_of(" \t\r\n");
    if (first == std::string::npos || last == std::string::npos ||
        output[first] != '{' || output[last] != '}') {
        return false;
    }
    const std::string normalized = output.substr(first, last - first + 1);
    if (normalized.find('\n') != std::string::npos || normalized.find('\r') != std::string::npos) {
        return false;
    }
    output = normalized;
    return true;
}

